<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Modules\Identity\Contracts\Enums\UserRole;
use App\Modules\Lookups\Contracts\Enums\LookupStatus;
use App\Modules\Providers\Contracts\Enums\Verdict;
use App\Modules\Shared\Enums\ApiErrorCode;
use App\Modules\Shared\Indicators\IndicatorType;
use BackedEnum;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Symfony\Component\Console\Output\OutputInterface;

/** Prints the shared PHP enums as TypeScript: `npm run contracts:export` at repo root; CI fails on drift. */
#[Signature('contracts:export {--schema : Print the enums as JSON Schema definitions (contracts/schemas/enums.schema.json)}')]
#[Description('Print shared enums and the lookup state machine as TypeScript')]
final class ExportContracts extends Command
{
    /** @var list<class-string<BackedEnum>> */
    private const array ENUMS = [
        LookupStatus::class,
        IndicatorType::class,
        Verdict::class,
        UserRole::class,
        ApiErrorCode::class,
    ];

    public function handle(): int
    {
        if ($this->option('schema') === true) {
            $this->getOutput()->write($this->schema(), false, OutputInterface::OUTPUT_RAW);

            return self::SUCCESS;
        }

        $blocks = array_map($this->enumBlock(...), self::ENUMS);
        $blocks[] = $this->stateMachineBlock();

        $this->getOutput()->write(
            "// AUTO-GENERATED by `php artisan contracts:export` from PHP enums in apps/api. Do not edit.\n\n"
            .implode("\n", $blocks),
            false,
            OutputInterface::OUTPUT_RAW,
        );

        return self::SUCCESS;
    }

    /** JSON Schema definitions referenced by the hand-written response schemas. */
    private function schema(): string
    {
        $definitions = [];
        foreach (self::ENUMS as $enum) {
            $definitions[class_basename($enum)] = [
                'type' => 'string',
                'enum' => array_map(static fn (BackedEnum $case): string => (string) $case->value, $enum::cases()),
            ];
        }

        return json_encode([
            '$schema' => 'http://json-schema.org/draft-07/schema#',
            '$id' => 'https://secnix.local/contracts/enums.schema.json',
            '$comment' => 'AUTO-GENERATED by `php artisan contracts:export --schema` from PHP enums in apps/api. Do not edit.',
            'title' => 'Enums',
            'definitions' => $definitions,
        ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR).'
';
    }

    /** @param class-string<BackedEnum> $enum */
    private function enumBlock(string $enum): string
    {
        $name = class_basename($enum);
        $members = array_map(
            static fn (BackedEnum $case): string => sprintf('  %s: %s,', $case->name, self::literal($case->value)),
            $enum::cases(),
        );

        return "export const {$name} = {\n".implode("\n", $members)."\n} as const;\n"
            ."export type {$name} = (typeof {$name})[keyof typeof {$name}];\n";
    }

    private function stateMachineBlock(): string
    {
        $transitions = array_map(
            static fn (LookupStatus $status): string => sprintf(
                '  %s: %s,',
                $status->value,
                self::list($status->allowedTransitions()),
            ),
            LookupStatus::cases(),
        );

        return "export const LOOKUP_STATUS_TRANSITIONS = {\n".implode("\n", $transitions)."\n}"
            ." as const satisfies Record<LookupStatus, readonly LookupStatus[]>;\n\n"
            .'export const ACTIVE_LOOKUP_STATUSES = '.self::list(LookupStatus::active())
            ." as const satisfies readonly LookupStatus[];\n";
    }

    /** @param list<LookupStatus> $statuses */
    private static function list(array $statuses): string
    {
        return '['.implode(', ', array_map(static fn (LookupStatus $s): string => self::literal($s->value), $statuses)).']';
    }

    private static function literal(int|string $value): string
    {
        return is_int($value) ? (string) $value : '"'.addcslashes($value, '"\\').'"';
    }
}
