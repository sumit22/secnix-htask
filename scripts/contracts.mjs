#!/usr/bin/env node
// Syncs the shared response contracts (contracts/schemas, the single source) into both apps:
//   apps/api/tests/Contracts/schemas/*  → API integration tests validate every response against them
//   apps/web/src/contracts/schemas/*    → the web app validates every response at runtime (ajv)
//   apps/web/src/contracts/api.generated.ts → TS types for the web app
// enums.schema.json is itself generated from PHP enums (php artisan contracts:export --schema).
// Usage: node scripts/contracts.mjs   (CI re-runs it and fails on any diff)
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'contracts', 'schemas');
const targets = [join(root, 'apps/api/tests/Contracts/schemas'), join(root, 'apps/web/src/contracts/schemas')];
const schemas = readdirSync(source).filter((f) => f.endsWith('.schema.json')).sort();

for (const dir of targets) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const file of schemas) copyFileSync(join(source, file), join(dir, file));
}

const { compile } = createRequire(join(root, 'apps/web/package.json'))('json-schema-to-typescript');
const banner = '// AUTO-GENERATED by `node scripts/contracts.mjs` from contracts/schemas. Do not edit.';
const parts = [];
for (const file of schemas.filter((f) => f !== 'enums.schema.json')) {
  const schema = JSON.parse(readFileSync(join(source, file), 'utf8'));
  parts.push(await compile(schema, schema.title, {
    cwd: source,
    bannerComment: '',
    additionalProperties: false,
    declareExternallyReferenced: true,
    format: true,
  }));
}
// Enum unions are inlined from enums.schema.json, which PHP generates: same values as generated.ts.
writeFileSync(join(root, 'apps/web/src/contracts/api.generated.ts'), `${banner}\n\n${parts.join('\n')}`);
console.log(`contracts: ${schemas.length} schemas synced, types generated`);
