#!/usr/bin/env node
// Exports Claude Code prompts, chat history and token usage for this project into docs/ai/.
// Source: ~/.claude/projects/<project-slug>/*.jsonl (+ <session>/subagents/*.jsonl).
// Runs automatically via the Stop hook in .claude/settings.json; safe to run manually.
// Override transcript dir with CLAUDE_TRANSCRIPTS_DIR.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'docs', 'ai');

function transcriptsDir() {
  if (process.env.CLAUDE_TRANSCRIPTS_DIR) return process.env.CLAUDE_TRANSCRIPTS_DIR;
  const slug = root.replace(/[^a-zA-Z0-9]/g, '-');
  const base = join(homedir(), '.claude', 'projects');
  for (const s of [slug, slug.charAt(0).toLowerCase() + slug.slice(1), slug.charAt(0).toUpperCase() + slug.slice(1)]) {
    if (existsSync(join(base, s))) return join(base, s);
  }
  return null;
}

const readJsonl = (file) =>
  readFileSync(file, 'utf8')
    .split('\n')
    .filter(Boolean)
    .flatMap((line) => {
      try { return [JSON.parse(line)]; } catch { return []; }
    });

const emptyUsage = () => ({ input: 0, output: 0, cacheWrite: 0, cacheRead: 0, requests: 0 });
function addUsage(acc, u) {
  acc.input += u.input_tokens ?? 0;
  acc.output += u.output_tokens ?? 0;
  acc.cacheWrite += u.cache_creation_input_tokens ?? 0;
  acc.cacheRead += u.cache_read_input_tokens ?? 0;
  acc.requests += 1;
}

// Sum usage per model, deduping by message id (one API response can span several JSONL lines).
function usageByModel(entries) {
  const seen = new Set();
  const byModel = {};
  for (const e of entries) {
    if (e.type !== 'assistant' || !e.message?.usage) continue;
    const id = e.message.id ?? e.uuid;
    if (seen.has(id)) continue;
    seen.add(id);
    const model = e.message.model ?? 'unknown';
    if (model === '<synthetic>') continue;
    addUsage((byModel[model] ??= emptyUsage()), e.message.usage);
  }
  return byModel;
}

const isHumanPrompt = (e) => e.type === 'user' && (e.origin?.kind === 'human' || e.turnOrigin === 'human') && !e.isMeta;
function promptText(e) {
  const c = e.message?.content;
  const blocks = typeof c === 'string' ? [c] : (c ?? []).filter((b) => b.type === 'text').map((b) => b.text);
  // Drop harness-injected context blocks (<system-reminder>, <browser_instruction>, ...).
  return blocks.filter((t) => !/^\s*<[a-z_-]+>/i.test(t)).join('\n\n').trim();
}
const assistantText = (e) =>
  (e.message?.content ?? []).filter((b) => b.type === 'text').map((b) => b.text).join('\n\n').trim();

const fmt = (n) => n.toLocaleString('en-US');
const total = (u) => u.input + u.output + u.cacheWrite + u.cacheRead;

const dir = transcriptsDir();
if (!dir) {
  console.error('ai-usage: transcript directory not found');
  process.exit(0);
}

const sessions = readdirSync(dir)
  .filter((f) => f.endsWith('.jsonl'))
  .map((f) => {
    const id = f.replace(/\.jsonl$/, '');
    const entries = readJsonl(join(dir, f));
    const subDir = join(dir, id, 'subagents');
    const subFiles = existsSync(subDir) ? readdirSync(subDir).filter((s) => s.endsWith('.jsonl')) : [];
    const subEntries = subFiles.flatMap((s) => readJsonl(join(subDir, s)));
    const stamps = entries.map((e) => e.timestamp).filter(Boolean).sort();
    return {
      id,
      entries,
      start: stamps[0] ?? '',
      end: stamps.at(-1) ?? '',
      main: usageByModel(entries),
      sub: usageByModel(subEntries),
      subagentCount: subFiles.length,
    };
  })
  .filter((s) => s.start)
  .sort((a, b) => a.start.localeCompare(b.start));

mkdirSync(outDir, { recursive: true });

// prompts.md + chat-history.md
const prompts = ['# Prompts used', '', '_Auto-generated by `scripts/ai-usage.mjs` from Claude Code transcripts. Verbatim user prompts, in order._', ''];
const chat = ['# Chat history', '', '_Auto-generated by `scripts/ai-usage.mjs`. User prompts and assistant replies (tool calls/outputs omitted)._', ''];
let n = 0;
for (const s of sessions) {
  chat.push(`## Session \`${s.id}\` (${s.start} → ${s.end})`, '');
  for (const e of s.entries) {
    if (isHumanPrompt(e)) {
      const t = promptText(e);
      if (!t) continue;
      n += 1;
      prompts.push(`## ${n}. ${e.timestamp}`, '', '```text', t, '```', '');
      chat.push(`### 🧑 User — ${e.timestamp}`, '', t, '');
    } else if (e.type === 'assistant' && !e.isSidechain) {
      const t = assistantText(e);
      if (t) chat.push(`### 🤖 Claude — ${e.timestamp}`, '', t, '');
    }
  }
}
writeFileSync(join(outDir, 'prompts.md'), prompts.join('\n'));
writeFileSync(join(outDir, 'chat-history.md'), chat.join('\n'));

// token-usage.md
const grand = emptyUsage();
const rows = [];
for (const s of sessions) {
  for (const [scope, byModel] of [['main', s.main], ['subagents', s.sub]]) {
    for (const [model, u] of Object.entries(byModel)) {
      rows.push(`| \`${s.id.slice(0, 8)}\` | ${scope} | ${model} | ${u.requests} | ${fmt(u.input)} | ${fmt(u.output)} | ${fmt(u.cacheWrite)} | ${fmt(u.cacheRead)} | ${fmt(total(u))} |`);
      for (const k of Object.keys(grand)) grand[k] += u[k];
    }
  }
}
const first = sessions[0]?.start ?? '';
const last = sessions.at(-1)?.end ?? '';
const mins = first && last ? Math.round((Date.parse(last) - Date.parse(first)) / 60000) : 0;
const usage = [
  '# Token usage',
  '',
  '_Auto-generated by `scripts/ai-usage.mjs` from Claude Code transcripts (deduped per API response). Cross-check with `/cost`._',
  '',
  `- First prompt: ${first}`,
  `- Last activity: ${last}`,
  `- Elapsed (wall clock, incl. idle): ${Math.floor(mins / 60)}h ${mins % 60}m`,
  `- Sessions: ${sessions.length} · Subagents: ${sessions.reduce((a, s) => a + s.subagentCount, 0)}`,
  '',
  '## Totals',
  '',
  '| Input | Output | Cache write | Cache read | Total | API calls |',
  '|---:|---:|---:|---:|---:|---:|',
  `| ${fmt(grand.input)} | ${fmt(grand.output)} | ${fmt(grand.cacheWrite)} | ${fmt(grand.cacheRead)} | ${fmt(total(grand))} | ${grand.requests} |`,
  '',
  '## By session / model',
  '',
  '| Session | Scope | Model | Calls | Input | Output | Cache write | Cache read | Total |',
  '|---|---|---|---:|---:|---:|---:|---:|---:|',
  ...rows,
  '',
];
writeFileSync(join(outDir, 'token-usage.md'), usage.join('\n'));

if (!process.argv.includes('--quiet')) {
  console.log(`ai-usage: ${n} prompts, ${sessions.length} sessions, ${fmt(total(grand))} tokens → docs/ai/`);
}
